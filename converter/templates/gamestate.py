import os, glob
from converter.config import GODOT_DIR, RAW_DIR


def _switch_numbers() -> set[int]:
    nums = set()
    for path in glob.glob(os.path.join(RAW_DIR, "*.obj")):
        lines = [l.strip() for l in open(path, "rb").read().decode("utf-8", "ignore").splitlines() if l.strip()]
        if len(lines) < 3 or lines[2].upper() != "SWITCH":
            continue
        for line in lines:
            if line.startswith("number="):
                try:
                    nums.add(int(line.split("=", 1)[1]))
                except ValueError:
                    pass
    return nums


def write_gamestate(popups: dict, level_flow: dict):
    out_path = os.path.join(GODOT_DIR, "scripts", "GameState.gd")
    lines = [
        "extends Node",
        "",
        "var switches: Dictionary = {}",
        f"var popups: Dictionary = {repr(popups)}",
        f"var level_order: Array = {repr(level_flow.get('order', []))}",
        f'var victory_scene: String = "{level_flow.get("victory", "")}"',
        f'var lose_scene: String = "{level_flow.get("lose", "")}"',
        f"var level_by_number: Dictionary = {repr(level_flow.get('by_number', {}))}",
        f"var known_switches: Array = {repr(sorted(_switch_numbers()))}",
        "var hp: int = 100",
        "var max_hp: int = 100",
        "var score: int = 0",
        "var keys: int = 0",
        "var cleared: Dictionary = {}",
        "var level_bottom: int = 100000",
        "",
        "var popup_panel: PanelContainer",
        "var popup_label: Label",
        "var is_popup_open: bool = false",
        "",
        "func _ready():",
        "\tprocess_mode = Node.PROCESS_MODE_ALWAYS",
        "\tvar layer = CanvasLayer.new()",
        "\tlayer.layer = 50",
        "\tadd_child(layer)",
        "\tpopup_panel = PanelContainer.new()",
        "\tpopup_panel.visible = false",
        "\tpopup_panel.set_anchors_preset(Control.PRESET_CENTER)",
        "\tpopup_panel.custom_minimum_size = Vector2(520, 220)",
        "\tpopup_panel.offset_left = -260",
        "\tpopup_panel.offset_top = -110",
        "\tpopup_panel.offset_right = 260",
        "\tpopup_panel.offset_bottom = 110",
        "\tlayer.add_child(popup_panel)",
        "\tpopup_label = Label.new()",
        "\tpopup_label.autowrap_mode = TextServer.AUTOWRAP_WORD_SMART",
        "\tpopup_label.horizontal_alignment = HORIZONTAL_ALIGNMENT_CENTER",
        "\tpopup_label.vertical_alignment = VERTICAL_ALIGNMENT_CENTER",
        "\tpopup_panel.add_child(popup_label)",
        "\t# Диалог ставит игру на паузу — снимаем её по сигналу окончания.",
        "\tvar dm = _dialogue_manager()",
        "\tif dm != null and dm.has_signal(\"dialogue_ended\"):",
        "\t\tdm.dialogue_ended.connect(_on_dialogue_ended)",
        "",
        "func _dialogue_manager():",
        "\tvar dm = get_node_or_null(\"/root/DialogueManager\")",
        "\tif dm == null:",
        "\t\tfor node in get_tree().root.get_children():",
        "\t\t\tif node.has_method(\"show_dialogue_balloon\"):",
        "\t\t\t\tdm = node",
        "\t\t\t\tbreak",
        "\treturn dm",
        "",
        "func _on_dialogue_ended(_resource = null):",
        "\tget_tree().paused = false",
        "",
        "func _process(_delta):",
        '\tif is_popup_open and Input.is_action_just_pressed("ui_accept"):',
        "\t\tpopup_panel.visible = false",
        "\t\tis_popup_open = false",
        "\t\tget_tree().paused = false",
        "",
        "func show_popup(idx: int):",
        "\tif idx <= 0 or not popups.has(idx):",
        "\t\treturn",
        "\t# Если установлен Dialogue Manager — используем его и ставим игру на паузу.",
        "\tvar dm = _dialogue_manager()",
        "\tvar dpath = \"res://dialogue/popup_%d.dialogue\" % idx",
        "\tif dm != null and ResourceLoader.exists(dpath):",
        "\t\tget_tree().paused = true",
        "\t\tdm.show_dialogue_balloon(load(dpath), \"start\")",
        "\t\treturn",
        '\tpopup_label.text = "\\n".join(popups[idx])',
        "\tpopup_panel.visible = true",
        "\tis_popup_open = true",
        "\tget_tree().paused = true",
        "",
        "func trigger_switch(num: int, mode: int = 2):",
        "\tif num <= 0:",
        "\t\treturn",
        "\tvar nxt = not switches.get(num, false) if mode == 2 else true",
        "\tswitches[num] = nxt",
        '\tget_tree().call_group("switch_listeners", "on_switch_event", num, nxt)',
        "",
        "func start_timer(tid: int, secs: float):",
        "\tif tid > 0:",
        '\t\tget_tree().call_group("game_timers", "on_start_timer", tid, secs)',
        "",
        "func add_score(pts: int):",
        "\tscore += pts",
        '\tget_tree().call_group("hud_score", "update_score", score)',
        "",
        "func damage_player(dmg: int):",
        "\thp = max(0, hp - dmg)",
        '\tget_tree().call_group("hud_health", "update_hp", hp, max_hp)',
        "\tif hp <= 0:",
        "\t\thp = max_hp",
        '\t\tif lose_scene != "":',
        "\t\t\tget_tree().change_scene_to_file(lose_scene)",
        "\t\telse:",
        "\t\t\tget_tree().reload_current_scene()",
        "",
        "func kill_player():",
        "\thp = 0",
        "\tget_tree().call_group(\"hud_health\", \"update_hp\", hp, max_hp)",
        "\tif lose_scene != \"\":",
        "\t\tget_tree().change_scene_to_file(lose_scene)",
        "\telse:",
        "\t\tget_tree().reload_current_scene()",
        "",
        "func mark_cleared(obj_id: String):",
        "\tcleared[obj_id] = true",
        "",
        "func is_cleared(obj_id: String) -> bool:",
        "\treturn cleared.get(obj_id, false)",
        "",
        "func go_to_level(num: int):",
        "\tif level_by_number.has(num):",
        "\t\tget_tree().change_scene_to_file(level_by_number[num])",
        "",
        "func on_timer_action(action: int, param: int):",
        "\tif param <= 0:",
        "\t\treturn",
        "\tif action == 2:",
        "\t\ttrigger_switch(param, 1)",
        "\telif action == 3:",
        "\t\t# В игре action=3 в основном дёргает свитч, но если numbers",
        "\t\t# совпадает с номером уровня и свитча с таким номером нет — идём дальше.",
        "\t\tif known_switches.has(param) or not level_by_number.has(param):",
        "\t\t\ttrigger_switch(param, 1)",
        "\t\telse:",
        "\t\t\tgo_to_level(param)",
        "\telif action == 1:",
        "\t\ttrigger_switch(param, 1)",
        "",
        "func next_level():",
        "\tvar cur = get_tree().current_scene.scene_file_path",
        "\tvar idx = level_order.find(cur)",
        "\tif idx >= 0 and idx + 1 < level_order.size():",
        "\t\tget_tree().change_scene_to_file(level_order[idx + 1])",
        '\telif victory_scene != "":',
        "\t\tget_tree().change_scene_to_file(victory_scene)",
        "\telse:",
        "\t\tget_tree().reload_current_scene()",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
